function regeneratePassiveYawBaseline()
% Rebuild the compact phase-seed-1 reference after an intentional rebaseline.
% Run with the pinned WEC-Sim source on the MATLAB path. This overwrites the
% checked-in IrrYaw_org.mat, so inspect the resulting regression diff.
caseDir = fileparts(mfilename('fullpath'));
originalDir = pwd;
cleanup = onCleanup(@() cd(originalDir));
cd(caseDir);
wecSim;
assert(strcmp(simu.solver, 'ode4') && simu.dt == 0.01 && ...
    simu.startTime == 0 && simu.endTime == 250 && ...
    waves.phaseSeed == 1 && body(1).yaw.threshold == 0 && ...
    body(2).yaw.threshold == 0, ...
    'The input does not match the continuous-heading regression');
referenceTime = output.bodies(1).time;
referenceYaw = output.bodies(1).position(:,6);
referenceForce = output.bodies(1).forceTotal(:,6);
referenceOmega = waves.omega(:);
referenceSpectrum = waves.spectrum(:);
referenceWave = waves.waveAmpTime(:,2);
assert(numel(referenceTime) == 25001 && ...
    isequal(size(referenceYaw),size(referenceTime), ...
        size(referenceForce),size(referenceWave)) && ...
    all(isfinite([referenceTime,referenceYaw,referenceForce, ...
        referenceWave]),'all'), 'Incomplete passive-yaw reference');
save('IrrYaw_org.mat','referenceTime','referenceYaw', ...
    'referenceForce','referenceOmega','referenceSpectrum', ...
    'referenceWave','-v7');
close_system('OSWEC',0);
end
